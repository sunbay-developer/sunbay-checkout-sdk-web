/**
 * CheckoutElement — the merchant-side Element handle (spec 6).
 *
 * Responsibilities:
 * - Constructed by `CheckoutInstance.create` (in unit tests, injected via a mock transport +
 *   constructor args).
 * - Mount a **visible** iframe at the merchant DOM target and forward Element commands through the
 *   transport.
 * - Maintain the state machine `created → loading → ready → destroyed` (with `loadError` as a side branch).
 * - Subscribe to the transport's `elementReady` / `loadError` events, filter by **its own elementId**,
 *   and drive the resolve / reject of `mount()`.
 *
 * Security constraint (AGENTS/spec): this layer only does DOM mounting and protocol command
 * forwarding and **never touches card values**. Card data exists only inside the hosted iframe and
 * is never transmitted via this handle or the transport.
 */

import {
    ErrorCode,
    isIframeResizeMessage,
    type Appearance,
    type AvailableWallets,
    type CheckoutError,
    type CommandName,
    type ElementOptions,
    type ElementStatus,
    type ElementType,
    type EventName,
    type EventPayloadMap,
    type ExpressAvailabilityChangeEvent,
    type ExpressCheckoutElementOptions,
} from '@sunbay/checkout-sdk-protocol';

/**
 * The minimal interface the transport depends on (satisfied by MainFrameTransport).
 *
 * Only declares the methods the Element handle needs, to make mock injection in unit tests easy.
 */
export interface ElementTransport {
    request(name: CommandName, payload: unknown): Promise<unknown>;
    on(event: EventName, handler: (payload: unknown) => void): void;
    off(event: EventName, handler: (payload: unknown) => void): void;
}

/** CheckoutElement constructor parameters (assembled by CheckoutInstance.create). */
export interface CheckoutElementOptions {
    /** Unique Element id (generated by the instance, used to pair commands/events). */
    elementId: string;
    /** Element type (determines the iframe path and available actions). */
    type: ElementType;
    /** Hosted page origin (without a trailing slash). */
    hostOrigin: string;
    /**
     * The current checkout session id. Sent with the iframe src as `?checkoutId=`, so that hosted
     * fields/element iframes join the correct same-origin signaling channel
     * (`sunbay-checkout:<checkoutId>`) and pair with main; missing it causes the field channel name
     * to mismatch and never become ready.
     */
    checkoutId: string;
    /** The transport layer. */
    transport: ElementTransport;
    /** Initial Element configuration (sent with createElement). */
    initialOptions?: ElementOptions;
    /**
     * Handle destruction callback (injected by CheckoutInstance). Called with this elementId when
     * `destroy()` successfully destroys the handle, so the instance removes itself from the
     * mutual-exclusion registry (elements Map), thereby allowing a mutually-exclusive Element of the
     * same kind to be recreated after destruction (e.g. switching expressCheckout's
     * buttonType/buttonHeight requires recreating the iframe). Not called by `unmount()` (which
     * keeps the handle, still occupies the slot, and can remount).
     */
    onDestroy?: (elementId: string) => void;
    /**
     * Initial color scheme (from createCheckout's appearance.colorScheme).
     * Only when provided is it appended to the iframe src's `&colorScheme=<value>`, so the hosted
     * iframe renders with that scheme on the first frame (no flash). When absent it is not appended
     * and the hosted side handles the default (light). Runtime switching goes through the
     * updateCheckout command, not here.
     */
    colorScheme?: 'light' | 'dark' | 'auto';
    /**
     * Initial appearance customization (from createCheckout's appearance).
     * Only when it contains `variables` or `rules` is it serialized into the iframe src's
     * `&appearance=<encodeURIComponent(JSON)>`, so the hosted iframe renders with that appearance on
     * the first frame (no flash). When it contains only `colorScheme` (no variables/rules) it is not
     * appended, to avoid an empty appearance string; colorScheme goes via the separate
     * `&colorScheme=`. Runtime switching goes through the updateCheckout command, not here.
     */
    appearance?: Appearance;
}

/** A merchant handler as stored internally (loosely typed; typing lives on the public methods). */
type UserHandler = (payload: unknown) => void;

/** The common structure of an event payload (contains elementId, used to filter by the own handle). */
interface WithElementId {
    elementId?: string;
}

/** The loadError event payload structure. */
interface LoadErrorPayload extends WithElementId {
    error: CheckoutError;
}

/** The elementReady event payload structure (expressCheckout additionally carries availableWallets). */
interface ElementReadyPayload extends WithElementId {
    availableWallets?: AvailableWallets;
}

/** The split field types (routed to /sdk/field/<type>). */
const FIELD_TYPES: readonly ElementType[] = ['cardNumber', 'cardExpiry', 'cardCvc'];

/** The input classes that provide focus/blur/clear (expressCheckout excluded). */
const INPUT_TYPES: readonly ElementType[] = [
    'cardNumber',
    'cardExpiry',
    'cardCvc',
    'card',
    'address',
];

/** Build a structured CheckoutError (configuration category, for the handle's local errors). */
function makeError(code: string, message: string, elementId?: string): CheckoutError {
    const rand = Math.random().toString(36).slice(2);
    return {
        code,
        message,
        category: 'configuration',
        errorId: `err_${Date.now().toString(36)}_${rand}`,
        elementId,
    };
}

/**
 * Determine whether the payload targets this elementId (**strict match**).
 *
 * Only when `payload.elementId === elementId` is it considered this Element's elementReady/loadError.
 * Missing elementId or inequality both fail to match, avoiding event cross-talk when multiple
 * Elements (T6) share the same transport.
 * (The protocol guarantees elementReady/loadError always carry an elementId.)
 */
function matchesElement(payload: unknown, elementId: string): boolean {
    if (typeof payload !== 'object' || payload === null) {
        return false;
    }
    return (payload as WithElementId).elementId === elementId;
}

export class CheckoutElement {
    /** Unique Element id. */
    readonly elementId: string;
    /** Element type. */
    readonly type: ElementType;
    /** The address Element's mode (billing/shipping; only meaningful for address), used by the instance to judge mutual exclusion by mode. */
    readonly mode: string | undefined;

    private readonly hostOrigin: string;
    private readonly checkoutId: string;
    private readonly transport: ElementTransport;
    private options: ElementOptions | undefined;
    /** Initial color scheme (appended to the iframe src; not appended when absent). */
    private readonly colorScheme: 'light' | 'dark' | 'auto' | undefined;
    /** Initial appearance customization (appended to the iframe src when it contains variables/rules; not appended when absent or colorScheme-only). */
    private readonly appearance: Appearance | undefined;
    /** Destruction callback (injected by the instance): called at the end of destroy() so the instance removes itself from the mutual-exclusion registry to free the slot. */
    private readonly onDestroy: ((elementId: string) => void) | undefined;

    private status: ElementStatus = 'created';
    private container: HTMLElement | null = null;
    private iframe: HTMLIFrameElement | null = null;

    /** Event handlers temporarily subscribed during mount (unbound after resolve/reject). */
    private readyHandler: ((payload: unknown) => void) | null = null;
    private loadErrorHandler: ((payload: unknown) => void) | null = null;

    /**
     * expressCheckout only: a snapshot of each wallet's availability.
     * Initially from elementReady.availableWallets, then updated by expressAvailabilityChange.
     */
    private availableWallets: AvailableWallets | undefined;
    /** expressCheckout only: the persistently subscribed expressAvailabilityChange handler (unbound on destroy). */
    private availabilityHandler: ((payload: unknown) => void) | null = null;

    /** Merchant listeners registered via `on`: event → (original handler → transport wrapper). Cleared on destroy. */
    private readonly userListeners = new Map<EventName, Map<UserHandler, UserHandler>>();

    /**
     * iframe auto-height: the window 'message' listener that stays resident during mount (unbound
     * when the iframe disappears/is destroyed). Keeps a reference so removeEventListener can be
     * called; null means not listening.
     */
    private resizeHandler: ((e: MessageEvent) => void) | null = null;
    /** The most recently applied iframe height (px), used for deduplication to avoid redundant style writes; null means not yet set. */
    private lastHeight: number | null = null;

    constructor(opts: CheckoutElementOptions) {
        this.elementId = opts.elementId;
        this.type = opts.type;
        this.hostOrigin = opts.hostOrigin;
        this.checkoutId = opts.checkoutId;
        this.transport = opts.transport;
        this.options = opts.initialOptions;
        this.colorScheme = opts.colorScheme;
        this.appearance = opts.appearance;
        this.mode = (opts.initialOptions as { mode?: string } | undefined)?.mode;
        this.onDestroy = opts.onDestroy;
        this.installInputActions();
        this.installExpressAvailability();
    }

    /** The current status (read-only snapshot, for external/test observation). */
    getStatus(): ElementStatus {
        return this.status;
    }

    /**
     * expressCheckout only: return the current snapshot of each wallet's availability (always
     * undefined for other types).
     *
     * The initial value comes from elementReady's availableWallets, then is updated by
     * expressAvailabilityChange.
     *
     * @returns The availability snapshot; undefined when not yet ready or non-express.
     */
    getAvailableWallets(): AvailableWallets | undefined {
        return this.availableWallets;
    }

    /**
     * Mount at the merchant DOM target: insert a visible iframe, send createElement, await elementReady.
     *
     * @param selectorOrEl - A CSS selector or an HTMLElement container; the container must be unique and empty.
     * @returns Resolves after elementReady; on failure removes the node and rejects (loadError / INVALID_OPTIONS).
     * @throws INSTANCE_DESTROYED when already destroyed.
     * @example
     * await element.mount('#card-field');
     */
    mount(selectorOrEl: string | HTMLElement): Promise<void> {
        this.assertAlive();

        if (this.status === 'loading' || this.status === 'ready') {
            return Promise.reject(
                makeError(
                    ErrorCode.ELEMENT_CONFLICT,
                    'This Element is already mounted; mount cannot be called twice',
                    this.elementId
                )
            );
        }

        const container = this.resolveContainer(selectorOrEl);
        if (!container) {
            return Promise.reject(
                makeError(
                    ErrorCode.INVALID_OPTIONS,
                    'Target container not found or not uniquely resolvable',
                    this.elementId
                )
            );
        }
        if (container.childElementCount > 0) {
            return Promise.reject(
                makeError(ErrorCode.INVALID_OPTIONS, 'Target container is not empty', this.elementId)
            );
        }

        this.status = 'loading';
        this.container = container;

        const iframe = document.createElement('iframe');
        iframe.src = this.resolveSrc();
        iframe.title = `sunbay-checkout-${this.type}`;
        iframe.setAttribute('data-element-id', this.elementId);
        // Grant the Permissions Policy features the hosted iframe needs for cross-origin payment
        // flows, each scoped to 'self' and the hostOrigin (not opened to any other origin):
        // - `payment`: the Payment Request API used by Apple Pay / Google Pay. Without it the
        //   browser denies the API inside this cross-origin iframe ("payment is not allowed in
        //   this document"); Safari 17+ specifically requires allow="payment" for cross-origin
        //   Apple Pay.
        // - `publickey-credentials-get`: WebAuthn get(), used by passkey / biometric payment
        //   verification (e.g. 3DS/SCA). Cross-origin iframes need it explicitly granted.
        // All element types carry the same allowlist so the SDK works uniformly regardless of
        // which element drives a wallet / WebAuthn flow.
        iframe.setAttribute(
            'allow',
            `payment 'self' ${this.hostOrigin}; publickey-credentials-get 'self' ${this.hostOrigin}`
        );
        iframe.style.border = '0';
        iframe.style.width = '100%';
        iframe.style.display = 'block';
        // Height is fully driven by the iframe auto-resize protocol (child reports a ceil()'d
        // height via postMessage; see installResizeListener). Disable the iframe's own scrollbar
        // so sub-pixel content height differences on high-DPR browsers never surface a spurious
        // scrollbar (observed on the express button at devicePixelRatio=2).
        iframe.setAttribute('scrolling', 'no');
        container.appendChild(iframe);
        this.iframe = iframe;
        this.installResizeListener();

        return new Promise<void>((resolve, reject) => {
            const cleanup = (): void => {
                if (this.readyHandler) {
                    this.transport.off('elementReady', this.readyHandler);
                    this.readyHandler = null;
                }
                if (this.loadErrorHandler) {
                    this.transport.off('loadError', this.loadErrorHandler);
                    this.loadErrorHandler = null;
                }
            };

            const onReady = (payload: unknown): void => {
                if (!matchesElement(payload, this.elementId)) {
                    return;
                }
                cleanup();
                // expressCheckout: capture the initial wallet availability carried by ready.
                const wallets = (payload as ElementReadyPayload).availableWallets;
                if (wallets) {
                    this.availableWallets = wallets;
                }
                this.status = 'ready';
                resolve();
            };

            const onLoadError = (payload: unknown): void => {
                if (!matchesElement(payload, this.elementId)) {
                    return;
                }
                cleanup();
                this.status = 'loadError';
                this.removeIframe();
                const err = (payload as LoadErrorPayload)?.error;
                reject(
                    err ??
                        makeError(
                            ErrorCode.RUNTIME_LOAD_FAILED,
                            'Failed to load Element',
                            this.elementId
                        )
                );
            };

            this.readyHandler = onReady;
            this.loadErrorHandler = onLoadError;
            this.transport.on('elementReady', onReady);
            this.transport.on('loadError', onLoadError);

            // Send the createElement command; a command-level failure also goes through the loadError side branch.
            this.transport
                .request('createElement', {
                    elementId: this.elementId,
                    type: this.type,
                    options: this.options,
                })
                .catch((cmdErr: unknown) => {
                    cleanup();
                    this.status = 'loadError';
                    this.removeIframe();
                    reject(cmdErr as CheckoutError);
                });
        });
    }

    /**
     * Unmount: send destroyElement, remove the iframe; idempotent; keeps the handle and configuration.
     *
     * @returns Resolves on completion (resolves directly when not mounted).
     * @throws INSTANCE_DESTROYED when already destroyed.
     */
    async unmount(): Promise<void> {
        this.assertAlive();
        if (this.status !== 'ready' && this.status !== 'loading') {
            // Not mounted: idempotent no-op.
            return;
        }
        try {
            await this.transport.request('destroyElement', { elementId: this.elementId });
        } finally {
            this.removeIframe();
            this.container = null;
            this.status = 'created';
        }
    }

    /**
     * Destroy the handle: idempotent; remove the iframe; afterwards any non-destroy/off call throws INSTANCE_DESTROYED.
     */
    destroy(): void {
        if (this.status === 'destroyed') {
            return;
        }
        if (this.readyHandler) {
            this.transport.off('elementReady', this.readyHandler);
            this.readyHandler = null;
        }
        if (this.loadErrorHandler) {
            this.transport.off('loadError', this.loadErrorHandler);
            this.loadErrorHandler = null;
        }
        if (this.availabilityHandler) {
            this.transport.off('expressAvailabilityChange', this.availabilityHandler);
            this.availabilityHandler = null;
        }
        for (const [event, wrappers] of this.userListeners) {
            for (const wrapper of wrappers.values()) {
                this.transport.off(event, wrapper);
            }
        }
        this.userListeners.clear();
        this.removeIframe();
        this.container = null;
        this.status = 'destroyed';
        // Notify the instance to remove itself from the mutual-exclusion registry, freeing the slot to allow recreating a mutually-exclusive Element of the same kind after destruction.
        this.onDestroy?.(this.elementId);
    }

    /**
     * Update the Element configuration: send updateElement; illegal fields are rejected wholesale by the hosted side.
     *
     * @param patch - Configuration delta.
     * @returns Resolves after successfully writing back the local options.
     * @throws INSTANCE_DESTROYED when already destroyed.
     */
    async update(patch: Partial<ElementOptions>): Promise<void> {
        this.assertAlive();
        const resp = await this.transport.request('updateElement', {
            elementId: this.elementId,
            patch,
        });
        const next = (resp as { options?: ElementOptions } | undefined)?.options;
        if (next) {
            this.options = next;
        }
    }

    /**
     * Register an event handler (passed through to the transport, dispatched by event name).
     *
     * @param event - Event name.
     * @param handler - Callback.
     * @throws INSTANCE_DESTROYED when already destroyed.
     */
    on<E extends EventName>(event: E, handler: (payload: EventPayloadMap[E]) => void): void {
        this.assertAlive();
        let wrappers = this.userListeners.get(event);
        if (!wrappers) {
            wrappers = new Map();
            this.userListeners.set(event, wrappers);
        }
        if (wrappers.has(handler as UserHandler)) {
            return;
        }
        // The only typed→loose cast: the transport is loosely typed and the protocol guarantees the
        // payload shape per event name. The wrapper scopes delivery to this element: payloads that
        // carry a different elementId are dropped, payloads without one pass through unchanged.
        const typed = handler as UserHandler;
        const wrapper = (payload: unknown): void => {
            const target = (payload as WithElementId | null | undefined)?.elementId;
            if (target !== undefined && target !== this.elementId) {
                return;
            }
            typed(payload);
        };
        wrappers.set(typed, wrapper);
        this.transport.on(event, wrapper);
    }

    /**
     * Unregister an event handler (still safe to call after destruction).
     *
     * @param event - Event name.
     * @param handler - The previously registered callback.
     */
    off<E extends EventName>(event: E, handler: (payload: EventPayloadMap[E]) => void): void {
        const wrappers = this.userListeners.get(event);
        const wrapper = wrappers?.get(handler as UserHandler);
        if (!wrappers || !wrapper) {
            return;
        }
        wrappers.delete(handler as UserHandler);
        this.transport.off(event, wrapper);
    }

    /** Focus (input classes only, not provided by expressCheckout). */
    focus?: () => Promise<void>;
    /** Blur (input classes only, not provided by expressCheckout). */
    blur?: () => Promise<void>;
    /** Clear (input classes only, not provided by expressCheckout). */
    clear?: () => Promise<void>;

    /** Install input-class action methods (automatically called after construction). */
    private installInputActions(): void {
        if (!INPUT_TYPES.includes(this.type)) {
            return;
        }
        this.focus = (): Promise<void> => this.sendAction('focus');
        this.blur = (): Promise<void> => this.sendAction('blur');
        this.clear = (): Promise<void> => this.sendAction('clear');
    }

    /**
     * expressCheckout only: persistently subscribe to expressAvailabilityChange and update the local availability snapshot.
     *
     * This event payload has no elementId; express is a singleton (guaranteed by CheckoutInstance),
     * so there is no need to filter by elementId. Non-express types do not subscribe.
     */
    private installExpressAvailability(): void {
        if (this.type !== 'expressCheckout') {
            return;
        }
        const handler = (payload: unknown): void => {
            if (typeof payload !== 'object' || payload === null) {
                return;
            }
            const wallets = (payload as ExpressAvailabilityChangeEvent).availableWallets;
            if (wallets) {
                this.availableWallets = wallets;
            }
        };
        this.availabilityHandler = handler;
        this.transport.on('expressAvailabilityChange', handler);
    }

    /** Send one input-class action command (synchronously throws INSTANCE_DESTROYED after destruction). */
    private sendAction(name: 'focus' | 'blur' | 'clear'): Promise<void> {
        this.assertAlive();
        return this.transport.request(name, { elementId: this.elementId }).then(() => undefined);
    }

    /** Throw INSTANCE_DESTROYED if already destroyed. */
    private assertAlive(): void {
        if (this.status === 'destroyed') {
            throw makeError(ErrorCode.INSTANCE_DESTROYED, 'Checkout instance has been destroyed', this.elementId);
        }
    }

    /** Resolve the mount container (the selector must uniquely match a single element). */
    private resolveContainer(selectorOrEl: string | HTMLElement): HTMLElement | null {
        if (typeof selectorOrEl !== 'string') {
            return selectorOrEl;
        }
        const nodes = document.querySelectorAll(selectorOrEl);
        if (nodes.length !== 1) {
            return null;
        }
        const node = nodes[0];
        return node instanceof HTMLElement ? node : null;
    }

    /**
     * Resolve the iframe src: split fields go to /sdk/field/, the rest to /sdk/element/, with
     * checkoutId and elementId; if an initial colorScheme is provided, append `&colorScheme=<value>`
     * (no flash on the first frame); if the initial appearance contains variables or rules, append
     * `&appearance=<encodeURIComponent(JSON.stringify(appearance))>` (takes effect on the first
     * frame, no flash). An appearance containing only colorScheme (no variables/rules) is not
     * appended, to avoid an empty appearance string. For expressCheckout, additionally append the
     * wallet toggles / per-wallet buttonType / global buttonHeight (see {@link resolveExpressQuery}).
     *
     * elementId is sent with the src so the hosted child echoes it verbatim in iframe-resize
     * messages, letting the parent window dispatch the height per handle among multiple iframes on
     * the same page.
     */
    private resolveSrc(): string {
        const segment = FIELD_TYPES.includes(this.type) ? 'field' : 'element';
        let query = `?checkoutId=${encodeURIComponent(this.checkoutId)}`;
        query += `&elementId=${encodeURIComponent(this.elementId)}`;
        // address: pass the mode (billing/shipping) through so the hosted page binds the
        // correct same-origin field channel (address:<mode>). Without it, both address
        // Elements fall back to the default mode and the second never pairs/readies.
        if (this.type === 'address') {
            const mode = (this.options as { mode?: string } | undefined)?.mode;
            if (mode) {
                query += `&mode=${encodeURIComponent(mode)}`;
            }
        }
        if (this.colorScheme) {
            query += `&colorScheme=${encodeURIComponent(this.colorScheme)}`;
        }
        // Effective appearance for the first frame: a per-element appearance (from
        // create(type, { appearance })) takes precedence over the instance-level appearance
        // (from createCheckout). Serialize only when it contains variables or rules (avoid an
        // empty appearance string; colorScheme is passed through separately).
        const effectiveAppearance = this.perElementAppearance() ?? this.appearance;
        if (effectiveAppearance && (effectiveAppearance.variables || effectiveAppearance.rules)) {
            query += `&appearance=${encodeURIComponent(JSON.stringify(effectiveAppearance))}`;
        }
        // expressCheckout: pass the express options from create's second argument (wallet toggles /
        // buttonType / buttonHeight) through to the hosted iframe, so the merchant's configuration
        // takes effect on the first frame (C1 broken-link fix).
        if (this.type === 'expressCheckout') {
            query += this.resolveExpressQuery();
        }
        return `${this.hostOrigin}/sdk/${segment}/${this.type}${query}`;
    }

    /**
     * Extract a per-element appearance (from the Element's own options, i.e. the second
     * argument of create(type, options)). Returns undefined when absent. Used so per-element
     * customization (e.g. CardFieldElementOptions.appearance) is honored on the first frame.
     */
    private perElementAppearance(): Appearance | undefined {
        const opts = this.options as { appearance?: Appearance } | undefined;
        return opts?.appearance;
    }

    /**
     * Build the expressCheckout-specific query fragment (only called for expressCheckout):
     * - a wallet explicitly set to `false` → `&applePay=false` / `&googlePay=false` (force hidden,
     *   preserving the existing toggle semantics; `true` / absent → automatic, no toggle appended);
     * - a wallet configured in object form containing `buttonType` → `&applePayButtonType=<v>` /
     *   `&googlePayButtonType=<v>` (boolean toggle / absent → not appended);
     * - global `buttonHeight` (a finite number) → `&buttonHeight=<n>`.
     *
     * Appended only when there is a value; empty strings are not appended. This fragment never
     * touches card values and only carries display configuration.
     *
     * @returns A query fragment starting with `&` (returns an empty string when nothing is appendable).
     */
    private resolveExpressQuery(): string {
        const options = this.options as ExpressCheckoutElementOptions | undefined;
        if (!options) {
            return '';
        }
        let query = '';
        const applePay = options.paymentMethods?.applePay;
        const googlePay = options.paymentMethods?.googlePay;
        // Wallet toggle: only an explicit false (force hidden) is sent, preserving the existing toggle semantics.
        if (applePay === false) {
            query += `&applePay=false`;
        }
        if (googlePay === false) {
            query += `&googlePay=false`;
        }
        // Per-wallet buttonType: sent only when in object form and containing buttonType.
        if (typeof applePay === 'object' && applePay.buttonType) {
            query += `&applePayButtonType=${encodeURIComponent(applePay.buttonType)}`;
        }
        if (typeof googlePay === 'object' && googlePay.buttonType) {
            query += `&googlePayButtonType=${encodeURIComponent(googlePay.buttonType)}`;
        }
        // Global button height: sent only when a finite number (the hosted side then clamps to [30,64]).
        if (typeof options.buttonHeight === 'number' && Number.isFinite(options.buttonHeight)) {
            query += `&buttonHeight=${encodeURIComponent(String(options.buttonHeight))}`;
        }
        return query;
    }

    /**
     * Install the iframe auto-height listener: subscribe to window 'message', only trust a valid
     * {@link IframeResizeMessage} from this iframe's `contentWindow` with origin === hostOrigin, and
     * when the elementId matches this handle, adjust the outer iframe's height to the content's real
     * height (width stays 100%).
     *
     * Security: first verify `event.source === iframe.contentWindow` (the key source check), then
     * verify `event.origin === hostOrigin` (a stricter same-origin check), to prevent cross-origin forgery.
     * Height deduplication: skip if identical to the last one, to avoid redundant style writes.
     */
    private installResizeListener(): void {
        const handler = (event: MessageEvent): void => {
            if (!this.iframe) {
                return;
            }
            if (event.source !== this.iframe.contentWindow) {
                return;
            }
            if (event.origin !== this.hostOrigin) {
                return;
            }
            if (!isIframeResizeMessage(event.data)) {
                return;
            }
            if (event.data.elementId !== this.elementId) {
                return;
            }
            const { height } = event.data;
            if (height === this.lastHeight) {
                return;
            }
            this.lastHeight = height;
            this.iframe.style.height = `${height}px`;
        };
        this.resizeHandler = handler;
        window.addEventListener('message', handler);
    }

    /** Unbind the iframe auto-height listener and reset the deduplication state (idempotent). */
    private teardownResizeListener(): void {
        if (this.resizeHandler) {
            window.removeEventListener('message', this.resizeHandler);
            this.resizeHandler = null;
        }
        this.lastHeight = null;
    }

    /** Remove the iframe DOM node (if present) and unbind the auto-height listener. */
    private removeIframe(): void {
        this.teardownResizeListener();
        if (this.iframe && this.iframe.parentNode) {
            this.iframe.parentNode.removeChild(this.iframe);
        }
        this.iframe = null;
    }

    /** Factory: equivalent to `new CheckoutElement(opts)` (a unified entry for CheckoutInstance). */
    static create(opts: CheckoutElementOptions): CheckoutElement {
        return new CheckoutElement(opts);
    }
}
